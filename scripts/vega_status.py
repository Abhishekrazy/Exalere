import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRIAGE = os.path.join(ROOT, ".tmp_shots", "vega_triage.json")
VEGA_CONFIG = os.path.join(ROOT, "lib", "services", "scrapers", "vega_site_config.dart")
PLUGIN_SERVICE = os.path.join(ROOT, "lib", "services", "plugin_service.dart")
PLUGINS_DART = os.path.join(ROOT, "lib", "plugins", "plugins.dart")
VERIFIED = os.path.join(ROOT, "lib", "services", "verified_providers.dart")
OUT = os.path.join(ROOT, "docs", "vega-porting-status.md")

# Pre-existing engines predate the Vega port and use their own ids.
ALIASES = {
    "drive": "moviesdrive",
    "uhd": "uhdmovies",
    "mod": "moviesmod",
    "luxmovies": "rogmovies",
    "castle": "circleftp",
    "4khdhub": "fourkhdhub",
    "moviebox": "moviebox",
    "dramacool": "dramachi",
    "multi": "multimovies",
    "uniquestream": "animestream",
    "vega": "vegamovies",
}


def read(path: str) -> str:
    with open(path, encoding="utf-8", errors="ignore") as handle:
        return handle.read()


def main() -> int:
    if not os.path.exists(TRIAGE):
        print("run scripts/vega_triage.py --probe first", file=sys.stderr)
        return 2

    rows = json.load(open(TRIAGE, encoding="utf-8"))

    # VegaSiteConfig ids include catalog-row ids (`latest`); drop those.
    config_ids = set(re.findall(r"id: '([a-z0-9_]+)'", read(VEGA_CONFIG))) - {"latest"}
    manifest_ids = set(
        re.findall(r"^    '([a-z0-9_]+)': ExalerePluginManifest", read(PLUGIN_SERVICE), re.M)
    )
    store_ids = set(
        re.findall(r"CommunityPluginItem\(\s*\n\s*id: '([a-z0-9_]+)'", read(PLUGIN_SERVICE))
    )
    branch_ids = set(re.findall(r"id == '([a-z0-9_]+)'", read(PLUGINS_DART)))
    verified = set(re.findall(r"^    '([a-z0-9_]+)',", read(VERIFIED), re.M))

    config_lower = {i.lower() for i in config_ids}
    branch_lower = {i.lower() for i in branch_ids}
    manifest_lower = {i.lower() for i in manifest_ids}
    store_lower = {i.lower() for i in store_ids}
    verified_lower = {i.lower() for i in verified}

    def matches(pid: str, known: set) -> bool:
        lowered = pid.lower()
        if lowered in known:
            return True
        alias = ALIASES.get(lowered)
        if alias and alias in known:
            return True
        return any(len(lowered) >= 4 and lowered in candidate for candidate in known)

    def engine_for(pid: str) -> str:
        if (
            matches(pid, config_lower)
            or matches(pid, branch_lower)
            or matches(pid, manifest_lower)
        ):
            return "yes"
        return "-"

    lines = [
        "# Vega provider porting status",
        "",
        "Generated by `scripts/vega_status.py`; do not edit by hand.",
        "",
        "* **engine** — `createPlugin` builds a real engine for the id.",
        "* **store** — the add-on appears in Settings → Add-ons.",
        "* **verified** — the headless self-test resolved a stream from it",
        "  (`flutter test test/provider_selftest_test.dart --dart-define=PROVIDERS=all`).",
        "  A listed provider without this badge is not promised to play.",
        "* **kind / http** — `scripts/vega_triage.py` classification and last probe result.",
        "",
    ]

    counts = {"total": 0, "engine": 0, "store": 0, "verified": 0}
    table = [
        "| provider | kind | http | engine | store | verified | note |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]

    for row in sorted(rows, key=lambda r: (r.get("kind") or "", r.get("id") or "")):
        pid = (row.get("id") or "").strip()
        if not pid:
            continue
        counts["total"] += 1
        engine = engine_for(pid)
        store = "yes" if matches(pid, store_lower) else "-"
        is_verified = "yes" if matches(pid, verified_lower) else "-"
        if engine != "-":
            counts["engine"] += 1
        if store == "yes":
            counts["store"] += 1
        if is_verified == "yes":
            counts["verified"] += 1
        note = (row.get("note") or "").replace("|", "/")
        table.append(
            f"| {pid} | {row.get('kind', '?')} | {row.get('http', '?')} | {engine} | "
            f"{store} | {is_verified} | {note} |"
        )

    lines += [
        f"**{counts['total']} providers · {counts['engine']} with an engine · "
        f"{counts['store']} in the store · {counts['verified']} verified.**",
        "",
    ]
    lines += table
    lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {OUT}: {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
