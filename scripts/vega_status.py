import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRIAGE = os.path.join(ROOT, ".tmp_shots", "vega_triage.json")
TRIAGE_COMMITTED = os.path.join(ROOT, "docs", "vega-triage.json")
# Overridable so the staleness rule can be exercised against a temp copy.
BLOCKERS = os.environ.get("VEGA_BLOCKERS") or os.path.join(
    ROOT, "docs", "vega-blockers.json"
)
VEGA_CONFIG = os.path.join(ROOT, "lib", "services", "scrapers", "vega_site_config.dart")
PLUGIN_SERVICE = os.path.join(ROOT, "lib", "services", "plugin_service.dart")
PLUGINS_DART = os.path.join(ROOT, "lib", "plugins", "plugins.dart")
VERIFIED = os.path.join(ROOT, "lib", "services", "verified_providers.dart")
OUT = os.environ.get("VEGA_STATUS_OUT") or os.path.join(
    ROOT, "docs", "vega-porting-status.md"
)

# A gate can close as easily as it can open: a reason recorded months ago is a
# claim about the past, so the doc names the ones due for another look.
STALE_DAYS = 90

# Pre-existing engines predate the Vega port and use their own ids.
ALIASES = {
    "drive": "moviesdrive",
    "uhd": "uhdmovies",
    "mod": "moviesmod",
    "luxmovies": "rogmovies",
    "4khdhub": "fourkhdhub",
    "moviebox": "moviebox",
    "dramacool": "dramachi",
    "multi": "multimovies",
    "uniquestream": "animestream",
    "vega": "vegamovies",
}


def probe_age(entry: dict, today=None) -> int | None:
    """Days since a blocker entry was last confirmed, or None if undated."""
    checked = (entry.get("checked") or "").strip()
    if not checked:
        return None
    import datetime

    try:
        stamp = datetime.date.fromisoformat(checked)
    except ValueError:
        return None
    now = today or datetime.date.today()
    return (now - stamp).days


def read(path: str) -> str:
    with open(path, encoding="utf-8", errors="ignore") as handle:
        return handle.read()


def main() -> int:
    # Prefer the local probe output; fall back to the committed ledger so CI
    # (and anyone without the probe cache) can regenerate the doc.
    source = TRIAGE if os.path.exists(TRIAGE) else TRIAGE_COMMITTED
    if not os.path.exists(source):
        print("run scripts/vega_triage.py --probe first", file=sys.stderr)
        return 2

    rows = json.load(open(source, encoding="utf-8"))

    # VegaSiteConfig ids include catalog-row ids (`latest`); drop those.
    config_ids = set(re.findall(r"id: '([a-z0-9_]+)'", read(VEGA_CONFIG))) - {"latest"}
    manifest_ids = set(
        re.findall(r"^    '([a-z0-9_]+)': ExalerePluginManifest", read(PLUGIN_SERVICE), re.M)
    )
    store_ids = set(
        re.findall(r"CommunityPluginItem\(\s*\n\s*id: '([a-z0-9_]+)'", read(PLUGIN_SERVICE))
    )
    branch_ids = set(re.findall(r"id == '([a-z0-9_]+)'", read(PLUGINS_DART)))
    verified_source = read(VERIFIED)
    verified = set(re.findall(r"^    '([a-z0-9_]+)',", verified_source, re.M))
    unavailable_block = verified_source.split("static const Map<String, String> unavailable", 1)[-1]
    unavailable = dict(
        re.findall(r"'([a-z0-9_]+)':\s*\n?\s*'([^']+)'", unavailable_block)
    )

    config_lower = {i.lower() for i in config_ids}
    branch_lower = {i.lower() for i in branch_ids}
    manifest_lower = {i.lower() for i in manifest_ids}
    store_lower = {i.lower() for i in store_ids}
    verified_lower = {i.lower() for i in verified}

    def matches(pid: str, known: set) -> bool:
        lowered = pid.lower()
        if lowered in known:
            return True
        alias = ALIASES.get(lowered)
        if alias and alias in known:
            return True
        return any(len(lowered) >= 4 and lowered in candidate for candidate in known)

    def engine_for(pid: str) -> str:
        if (
            matches(pid, config_lower)
            or matches(pid, branch_lower)
            or matches(pid, manifest_lower)
        ):
            return "yes"
        return "-"

    lines = [
        "# Vega provider porting status",
        "",
        "Generated by `scripts/vega_status.py`; do not edit by hand.",
        "",
        "* **engine** — `createPlugin` builds a real engine for the id.",
        "* **store** — the add-on appears in Settings → Add-ons.",
        "* **verified** — the headless self-test resolved a stream from it",
        "  (`flutter test test/provider_selftest_test.dart --dart-define=PROVIDERS=all`).",
        "  A listed provider without this badge is not promised to play.",
        "* **kind / http** — `scripts/vega_triage.py` classification and last probe result.",
        "",
    ]

    counts = {"total": 0, "engine": 0, "store": 0, "verified": 0}
    table = [
        "| provider | kind | http | engine | store | verified | note |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]

    for row in sorted(rows, key=lambda r: (r.get("kind") or "", r.get("id") or "")):
        pid = (row.get("id") or "").strip()
        if not pid:
            continue
        counts["total"] += 1
        engine = engine_for(pid)
        store = "yes" if matches(pid, store_lower) else "-"
        is_verified = "yes" if matches(pid, verified_lower) else "-"
        if engine != "-":
            counts["engine"] += 1
        if store == "yes":
            counts["store"] += 1
        if is_verified == "yes":
            counts["verified"] += 1
        note = (row.get("note") or "").replace("|", "/")
        table.append(
            f"| {pid} | {row.get('kind', '?')} | {row.get('http', '?')} | {engine} | "
            f"{store} | {is_verified} | {note} |"
        )

    lines += [
        f"**{counts['total']} providers · {counts['engine']} with an engine · "
        f"{counts['store']} in the store · {counts['verified']} verified.**",
        "",
    ]
    blockers = {}
    if os.path.exists(BLOCKERS):
        blockers = json.load(open(BLOCKERS, encoding="utf-8")).get("providers", {})

    # Every provider without an engine must say why, or the ledger is a
    # half-truth: a reader cannot tell "not ported yet" from "forgotten".
    unported = [row["id"] for row in rows if engine_for(row["id"]) == "-"]
    unrecorded = [pid for pid in unported if pid not in blockers]
    if unrecorded:
        print(
            "blockers missing for: " + ", ".join(sorted(unrecorded)),
            file=sys.stderr,
        )
        return 3

    if blockers:
        families = {}
        for provider_id, entry in sorted(blockers.items()):
            families.setdefault(entry.get("family", "other"), []).append(
                (provider_id, entry)
            )

        lines += [
            "",
            "## Why the rest stay out",
            "",
            "One row per family of blockers, so a future round knows which class to",
            "re-probe instead of walking all 55 again. `docs/vega-blockers.json` is",
            "the machine-readable copy and records the date each was last confirmed.",
            "",
            "| Family | Providers, and what blocks each |",
            "| --- | --- |",
        ]
        for family, members in sorted(families.items()):
            cells = "<br>".join(
                f"`{pid}` — {entry.get('reason', '')}" for pid, entry in members
            )
            lines.append(f"| {family} | {cells} |")
        lines.append("")

    aged = []
    for provider_id, entry in blockers.items():
        days = probe_age(entry)
        if days is None:
            aged.append((provider_id, None, entry))
        elif days > STALE_DAYS:
            aged.append((provider_id, days, entry))

    if aged:
        aged.sort(key=lambda row: -(row[1] or 10**6))
        lines += [
            "## Probes due for another look",
            "",
            f"Recorded more than {STALE_DAYS} days ago (or never dated). A gate can",
            "open as easily as it can close, so these want a fresh probe before",
            "they are quoted as current.",
            "",
        ]
        for provider_id, days, entry in aged:
            when = "never dated" if days is None else f"{days} days ago"
            lines.append(
                f"* `{provider_id}` — {entry.get('family', 'other')} — {when}"
            )
        lines.append("")

    if unavailable:
        lines += [
            "## Listed but currently unavailable",
            "",
            "The store tags these `Unavailable` instead of `Verified`; remove the",
            "entry in `verified_providers.dart` once the headless self-test passes.",
            "",
        ]
        for provider_id, reason in unavailable.items():
            lines.append(f"* `{provider_id}` — {reason}")
        lines.append("")
    lines += table
    lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    stale_count = sum(1 for row in aged if row[1] is None or row[1] > STALE_DAYS)
    print(f"wrote {OUT}: {counts} · {stale_count} probe(s) due for another look")
    if "--strict-stale" in sys.argv and stale_count:
        return 4
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
